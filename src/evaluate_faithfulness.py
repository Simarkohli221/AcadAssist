"""
evaluate_faithfulness.py
-------------------------
Real-world faithfulness + answerability validation for RAKA.

WHY this script exists
-----------------------
The faithfulness classifier (models/faithfulness_lr.joblib) was trained and
evaluated entirely on data/faithfulness/dataset.csv, which is *synthetically*
generated by create_faithfulness_dataset.py (single/paired sentences as
positives; mutated numbers, cross-chunk swaps, off-topic filler as
negatives). That measures whether the classifier can tell a real source
sentence from an unrelated one — not whether it catches the hallucinations
an actual LLM (Groq) actually produces on real questions.

This script is a completely separate, held-out evaluation: a hand-curated
set of realistic questions about the real SPIT documents, run through the
ACTUAL shared pipeline (src/pipeline.py — the same code path chat.py and
web_server.py use), with the verifier's score/decision captured alongside
the retrieved context so a human can independently judge each answer.

FAITHFULNESS vs. ANSWERABILITY — these are deliberately two separate axes
--------------------------------------------------------------------------
It is tempting to conflate "the system didn't hallucinate" with "the system
gave a good answer", but they measure different failure modes and must be
judged (and scored) independently:

  human_faithfulness — is every substantive factual claim in the answer
    actually supported by context_used?
      1 = every substantive claim is supported.
      0 = at least one substantive claim is unsupported or contradicted.
    A safe refusal/abstention ("I could not find this information...")
    ordinarily contains no factual claim at all, so it should normally be
    human_faithfulness=1 — an abstention is not automatically unfaithful.

  human_answerability — did the system actually answer the user's question,
    sufficiently, using information available in context_used?
      1 = the question is adequately answered.
      0 = it is not adequately answered — including an UNNECESSARY
          abstention when context_used actually contained enough
          information to answer.

  A single answer can land in any combination of these two independently:
  e.g. a correct, fully-grounded partial answer can be faithful (1) yet not
  sufficiently answer the question (0); an unnecessary "I could not find
  this" refusal when the context clearly had the answer is faithful (1,
  nothing false was claimed) yet not answerable (0). Do not average or
  otherwise combine the two into a single score.

This script does NOT:
  - touch data/faithfulness/dataset.csv (the synthetic training set)
  - retrain or modify models/faithfulness_lr.joblib
  - modify the retriever, reranker, generator, or FaithfulnessVerifier logic
  - modify the 45-question validation set
  - assign either human label itself — human_faithfulness and
    human_answerability are both left blank for a person to fill in after
    reading `answer` against `context_used`; neither is ever derived from
    verifier_decision

Usage
-----
Phase 1 — run the pipeline over the validation set and capture results:
    python src/evaluate_faithfulness.py
    python src/evaluate_faithfulness.py --limit 5        # smoke-test a subset
    python src/evaluate_faithfulness.py --delay 20        # slower pacing (Groq TPM guard)

    Writes data/faithfulness/real_validation.csv with human_faithfulness and
    human_answerability both blank. A 15s (default, --delay to change) pause
    runs between questions, and generation uses a smaller max_tokens for
    this run only, both to stay under Groq's 8000 TPM limit. If the LLM
    call itself still fails (e.g. HTTP 429), that row is recorded with
    status="api_error" and the real error message preserved, and the run
    continues — it is never counted as successful and never scored.

Phase 2 — after manually filling in human_faithfulness and/or
human_answerability (0 or 1) for as many rows as you've reviewed:
    python src/evaluate_faithfulness.py --metrics

    Reads the same CSV back and reports faithfulness metrics (confusion
    matrix / accuracy / precision / recall / F1 / FPR / FNR) and
    answerability metrics (accuracy / precision / recall / F1) SEPARATELY,
    using only rows where status == "success" and the relevant human label
    is 0 or 1.
"""
