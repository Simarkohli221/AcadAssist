# Set by _capture_llm_errors' wrapper whenever the LLM backend call itself
# raises (HTTP 429 rate limit, timeout, unreachable, malformed response,
# etc.), then read back by run_evaluation() right after each run_pipeline()
# call. Generator.generate() already catches and falls back to
# NO_ANSWER_RESPONSE on exactly this exception (production behaviour,
# untouched), which means run_pipeline() returns normally instead of
# raising — so this is the only way to tell "the LLM legitimately said it
# couldn't find the answer" apart from "the API call failed and we're
# looking at the same fallback text". Single-threaded, sequential loop, so
# a plain module global is enough here.
_LAST_LLM_ERROR: str | None = None


def _capture_llm_errors(generator: Generator) -> None:
    """
    Wrap generator._backend.complete() to observe (not swallow) API/LLM
    failures, without changing generator.py's own error handling in any
    way: Generator.generate() still catches the exact same exception and
    falls back to NO_ANSWER_RESPONSE exactly as it does in production. This
    wrapper just records what happened, on the side, so this script can
    flag the row as an API failure instead of silently scoring a fallback
    message as if it were a genuine faithfulness verdict.
    """
    backend = generator._backend
    original_complete = backend.complete

    def _complete_and_record(system_prompt: str, user_prompt: str) -> str:
        global _LAST_LLM_ERROR
        try:
            return original_complete(system_prompt, user_prompt)
        except Exception as exc:
            _LAST_LLM_ERROR = str(exc)
            raise

    backend.complete = _complete_and_record


def _build_components():
    """Load the same components chat.py / web_server.py load. Read-only —
    nothing here trains or mutates the retriever, reranker, generator, or
    the faithfulness model.

    generator_module.MAX_TOKENS is overridden for this process only (see
    VALIDATION_MAX_TOKENS above) to reduce Groq TPM usage during a 45-call
    batch run; this is a runtime attribute set on the already-imported
    module object, not an edit to generator.py, so chat.py/web_server.py —
    separate processes with their own fresh import — keep MAX_TOKENS=768.
    """
    generator_module.MAX_TOKENS = VALIDATION_MAX_TOKENS

    retriever = Retriever.load(INDEX_DIR)
    reranker = get_reranker(retriever._embedder)
    generator = Generator()
    _capture_llm_errors(generator)
    verifier = FaithfulnessVerifier(embedder=retriever._embedder, index_dir=INDEX_DIR)
    return retriever, reranker, generator, verifier


def _empty_row(qid: str, category: str, question: str, error: str, latency_ms: int) -> dict:
    """A row for a question where run_pipeline() itself raised (retrieval/
    reranking/verifier failure — not an LLM/API call failure, see
    _api_error_row for that). status="error": never given either human
    label, never counted as successful, excluded from all metrics."""
    return {
        "id": qid,
        "category": category,
        "question": question,
        "human_faithfulness": "",
        "human_answerability": "",
        "status": "error",
        "verifier_decision": "",
        "faithfulness_score": "",
        "semantic_similarity": "",
        "keyword_jaccard": "",
        "numeric_consistency": "",
        "answer": "",
        "raw_answer": "",
        "warning": "",
        "normalized_query": "",
        "pipeline_category": "",
        "backend": "",
        "model": "",
        "mock": "",
        "latency_ms": latency_ms,
        "sources_json": "",
        "context_used": "",
        "error": error,
    }


def _api_error_row(qid: str, category: str, question: str, error: str, latency_ms: int, result) -> dict:
    """
    A row for a question where retrieval/reranking succeeded but the LLM
    call itself failed (Groq 429 rate limit, timeout, etc.) — detected via
    _LAST_LLM_ERROR after a run_pipeline() call that did NOT raise (because
    Generator.generate() swallows this exact exception into a fallback
    answer). status="api_error": never faithful/uncertain/unfaithful,
    never counted as a successful evaluation, never given either human
    label, and excluded from --metrics.

    context_used/sources/latency/backend/model are still preserved from
    `result` for diagnostics (retrieval happened before the failed LLM
    call), but answer/raw_answer/warning are blanked out rather than
    storing the misleading NO_ANSWER_RESPONSE fallback text as if it were
    a real model answer.
    """
    return {
        "id": qid,
        "category": category,
        "question": question,
        "human_faithfulness": "",
        "human_answerability": "",
        "status": "api_error",
        "verifier_decision": "",
        "faithfulness_score": "",
        "semantic_similarity": "",
        "keyword_jaccard": "",
        "numeric_consistency": "",
        "answer": "",
        "raw_answer": "",
        "warning": "",
        "normalized_query": result.normalized_query,
        "pipeline_category": result.category,
        "backend": result.backend,
        "model": result.model,
        "mock": result.mock,
        "latency_ms": latency_ms,
        "sources_json": json.dumps(result.sources, ensure_ascii=False),
        "context_used": result.context_used,
        "error": error,
    }


def run_evaluation(limit: int | None = None, delay: float = DEFAULT_DELAY_SECONDS) -> None:
    global _LAST_LLM_ERROR

    questions = VALIDATION_SET[:limit] if limit else VALIDATION_SET
    total = len(questions)

    print("Loading RAKA pipeline components (retriever, reranker, generator, faithfulness verifier)...")
    retriever, reranker, generator, verifier = _build_components()
    print(f"Components ready. Running {total} validation questions through src/pipeline.run_pipeline().")
    print(f"Delay between questions: {delay:.1f}s (Groq TPM guard). Generation max_tokens={VALIDATION_MAX_TOKENS} for this run.\n")

    rows: list[dict] = []
    n_ok = 0
    n_api_errors = 0
    n_pipeline_errors = 0
    status_counts = {"faithful": 0, "uncertain": 0, "unfaithful": 0}

    for i, item in enumerate(questions, start=1):
        qid, category, question = item["id"], item["category"], item["question"]
        print(f"[{i}/{total}] ({category}) {question}")

        _LAST_LLM_ERROR = None
        t0 = time.time()
        try:
            result = run_pipeline(question, retriever, reranker, generator, verifier)
            elapsed_ms = int((time.time() - t0) * 1000)

            if _LAST_LLM_ERROR:
                # The LLM call failed (e.g. HTTP 429) but Generator.generate()
                # caught it and returned its normal fallback response, so
                # run_pipeline() didn't raise. Record it as an API failure,
                # not a faithfulness/answerability verdict.
                row = _api_error_row(qid, category, question, _LAST_LLM_ERROR, elapsed_ms, result)
                n_api_errors += 1
                print(f"    -> API_ERROR: {_LAST_LLM_ERROR}")
            else:
                features = result.faithfulness_features or {}
                row = {
                    "id": qid,
                    "category": category,
                    "question": question,
                    "human_faithfulness": "",
                    "human_answerability": "",
                    "status": "success",
                    "verifier_decision": result.faithfulness_status,
                    "faithfulness_score": f"{result.faithfulness_score:.6f}",
                    "semantic_similarity": features.get("semantic_similarity", ""),
                    "keyword_jaccard": features.get("keyword_jaccard", ""),
                    "numeric_consistency": features.get("numeric_consistency", ""),
                    "answer": result.answer,
                    "raw_answer": result.raw_answer,
                    "warning": result.warning or "",
                    "normalized_query": result.normalized_query,
                    "pipeline_category": result.category,
                    "backend": result.backend,
                    "model": result.model,
                    "mock": result.mock,
                    "latency_ms": elapsed_ms,
                    "sources_json": json.dumps(result.sources, ensure_ascii=False),
                    "context_used": result.context_used,
                    "error": "",
                }
                status_counts[result.faithfulness_status] = status_counts.get(result.faithfulness_status, 0) + 1
                n_ok += 1
                print(f"    -> {result.faithfulness_status} (score={result.faithfulness_score:.3f}, {elapsed_ms}ms)")

        except Exception as exc:
            # Anything that escapes run_pipeline() itself (retrieval/
            # reranking/verifier failure) — distinct from an LLM/API
            # failure, which is caught above via _LAST_LLM_ERROR instead.
            # Never counted as successful, never scored, either way.
            elapsed_ms = int((time.time() - t0) * 1000)
            error_msg = f"{type(exc).__name__}: {exc}"
            row = _empty_row(qid, category, question, error_msg, elapsed_ms)
            n_pipeline_errors += 1
            print(f"    -> ERROR: {error_msg}")

        rows.append(row)

        if delay > 0 and i < total:
            time.sleep(delay)

    OUTPUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        writer.writerows(rows)

    print("\n" + "=" * 70)
    print("EVALUATION SUMMARY")
    print("=" * 70)
    print(f"Total questions:        {total}")
    print(f"Successful evaluations: {n_ok}")
    print(f"API failures:           {n_api_errors}")
    print(f"Faithful:               {status_counts['faithful']}")
    print(f"Uncertain:              {status_counts['uncertain']}")
    print(f"Unfaithful:             {status_counts['unfaithful']}")
    if n_pipeline_errors:
        print(f"Other pipeline errors:  {n_pipeline_errors}  (retrieval/reranking/verifier failure, not an API failure)")
    print(f"\nResults written to: {OUTPUT_CSV}")
    print("Next step: open the CSV, read `answer` against `context_used` for each row, and fill in:")
    print("  human_faithfulness  (1 = every substantive claim is supported, 0 = at least one is not)")
    print("  human_answerability (1 = the question is adequately answered, 0 = it is not)")
    print("(Leave both blank for any status=api_error/error row.)")
    print("Then run: python src/evaluate_faithfulness.py --metrics")


# ─────────────────────────────────────────────────────────────────────────
# Phase 2: score faithfulness and answerability SEPARATELY against the
# corresponding human labels (run after manual review)
# ─────────────────────────────────────────────────────────────────────────
def _safe_div(numerator: float, denominator: float) -> float:
    return numerator / denominator if denominator else float("nan")


def _label_is_binary(value: str | None) -> bool:
    return (value or "").strip() in ("0", "1")


def _binary_metrics(pairs: list[tuple[int, int]]) -> dict[str, float]:
    """pairs: list of (predicted, human), both 0/1. Returns raw confusion
    counts plus accuracy/precision/recall/F1/FPR/FNR. NaN where a ratio's
    denominator is zero (e.g. no positive predictions => precision=NaN)."""
    tp = fp = tn = fn = 0
    for predicted, human in pairs:
        if predicted == 1 and human == 1:
            tp += 1
        elif predicted == 1 and human == 0:
            fp += 1
        elif predicted == 0 and human == 0:
            tn += 1
        else:  # predicted == 0 and human == 1
            fn += 1

    total = tp + fp + tn + fn
    precision = _safe_div(tp, tp + fp)
    recall = _safe_div(tp, tp + fn)
    f1 = (
        _safe_div(2 * precision * recall, precision + recall)
        if not (math.isnan(precision) or math.isnan(recall))
        else float("nan")
    )
    return {
        "tp": tp, "fp": fp, "tn": tn, "fn": fn,
        "accuracy": _safe_div(tp + tn, total),
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "fpr": _safe_div(fp, fp + tn),
        "fnr": _safe_div(fn, fn + tp),
    }


def _print_confusion_matrix(m: dict[str, float], pos_label: str, neg_label: str) -> None:
    print(f"                          human={pos_label:<10}   human={neg_label}")
    print(f"predicted=1                  {m['tp']:>6}               {m['fp']:>6}")
    print(f"predicted=0                  {m['fn']:>6}               {m['tn']:>6}")


def _answer_is_substantive(answer: str) -> bool:
    """True if the final answer is neither the faithfulness gate's safe-
    substitute message nor the generator's own abstention text — i.e. the
    system attempted a real answer rather than declining. Used as the
    system's implicit "predicted answerable" signal, since RAKA has no
    explicit answerability classifier of its own to compare against."""
    text = (answer or "").strip()
    return text not in (SAFE_ANSWER, NO_ANSWER_RESPONSE)


def compute_metrics(csv_path: Path = OUTPUT_CSV) -> None:
    """
    Report faithfulness and answerability metrics SEPARATELY. Both use only
    rows where status == "success"; api_error/error rows are excluded even
    if a human label was mistakenly filled in for one.

    Faithfulness: predicted=1 iff verifier_decision == "faithful" (only
    "faithful" lets an answer through the gate unmodified; "uncertain" and
    "unfaithful" both collapse to predicted=0), compared against
    human_faithfulness.

    Answerability: predicted=1 iff the final `answer` is a substantive
    response rather than the gate's safe-substitute or the generator's own
    abstention text (see _answer_is_substantive), compared against
    human_answerability. RAKA has no dedicated answerability classifier —
    this is the closest available proxy for "did the system believe it
    answered" — so treat this comparison as informative rather than as a
    property the pipeline was explicitly trained to optimize.
    """
    if not csv_path.exists():
        print(f"No results file found at {csv_path}.")
        print("Run the evaluation first: python src/evaluate_faithfulness.py")
        return

    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    total_rows = len(rows)
    successful_rows = [r for r in rows if r.get("status") == "success"]
    api_error_rows = [r for r in rows if r.get("status") == "api_error"]
    other_error_rows = [r for r in rows if r.get("status") == "error"]

    faith_labeled = [r for r in successful_rows if _label_is_binary(r.get("human_faithfulness"))]
    faith_unlabeled = [r for r in successful_rows if not _label_is_binary(r.get("human_faithfulness"))]

    answer_labeled = [r for r in successful_rows if _label_is_binary(r.get("human_answerability"))]
    answer_unlabeled = [r for r in successful_rows if not _label_is_binary(r.get("human_answerability"))]

    print(f"Total rows:                    {total_rows}")
    print(f"Successful rows:               {len(successful_rows)}")
    print(f"API errors:                    {len(api_error_rows)}")
    if other_error_rows:
        print(f"Other pipeline errors:         {len(other_error_rows)}")
    print(f"Unlabeled faithfulness rows:   {len(faith_unlabeled)}")
    print(f"Unlabeled answerability rows:  {len(answer_unlabeled)}")

    # ── Faithfulness metrics ────────────────────────────────────────────
    print("\n" + "=" * 70)
    print("FAITHFULNESS METRICS  (human_faithfulness vs. verifier_decision)")
    print("=" * 70)
    if not faith_labeled:
        print("No faithfulness-labeled rows yet — nothing to compute.")
    else:
        pairs = [
            (1 if r.get("verifier_decision") == "faithful" else 0, int(r["human_faithfulness"]))
            for r in faith_labeled
        ]
        m = _binary_metrics(pairs)
        print(f"Labeled rows used: {len(pairs)}")
        print("\n--- Confusion Matrix (predicted vs. human_faithfulness) ---")
        _print_confusion_matrix(m, pos_label="faithful(1)", neg_label="unfaithful(0)")
        print("(predicted=1 iff verifier_decision=='faithful'; 'uncertain' and 'unfaithful' both collapse")
        print(" to predicted=0, since only 'faithful' lets an answer through the gate unmodified.)")
        print("\n--- Metrics ---")
        print(f"Accuracy:             {m['accuracy']:.3f}")
        print(f"Precision:            {m['precision']:.3f}")
        print(f"Recall:               {m['recall']:.3f}")
        print(f"F1:                   {m['f1']:.3f}")
        print(f"False Positive Rate:  {m['fpr']:.3f}   (unfaithful answers the gate called faithful)")
        print(f"False Negative Rate:  {m['fnr']:.3f}   (faithful answers the gate blocked/warned on)")

    # ── Answerability metrics ───────────────────────────────────────────
    print("\n" + "=" * 70)
    print("ANSWERABILITY METRICS  (human_answerability vs. system behavior)")
    print("=" * 70)
    if not answer_labeled:
        print("No answerability-labeled rows yet — nothing to compute.")
    else:
        pairs = [
            (1 if _answer_is_substantive(r.get("answer")) else 0, int(r["human_answerability"]))
            for r in answer_labeled
        ]
        m = _binary_metrics(pairs)
        print(f"Labeled rows used: {len(pairs)}")
        print("\n--- Confusion Matrix (predicted vs. human_answerability) ---")
        _print_confusion_matrix(m, pos_label="answered(1)", neg_label="not-answered(0)")
        print("(predicted=1 iff the final answer is substantive, i.e. neither the faithfulness gate's")
        print(" safe-substitute message nor the generator's own 'could not find' abstention.)")
        print("\n--- Metrics ---")
        print(f"Accuracy:   {m['accuracy']:.3f}")
        print(f"Precision:  {m['precision']:.3f}")
        print(f"Recall:     {m['recall']:.3f}")
        print(f"F1:         {m['f1']:.3f}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Real-world faithfulness + answerability validation for RAKA (held-out from the synthetic training dataset).")
    parser.add_argument(
        "--metrics",
        action="store_true",
        help="Score verifier_decision/answer against human_faithfulness/human_answerability in the existing results CSV, instead of running the pipeline.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Only run the first N validation questions (for a quick smoke test instead of all 45).",
    )
    parser.add_argument(
        "--delay",
        type=float,
        default=DEFAULT_DELAY_SECONDS,
        help=f"Seconds to wait between questions, to stay under Groq's TPM rate limit (default: {DEFAULT_DELAY_SECONDS}).",
    )
    args = parser.parse_args()

    if args.metrics:
        compute_metrics()
    else:
        run_evaluation(limit=args.limit, delay=args.delay)


if __name__ == "__main__":
    main()
